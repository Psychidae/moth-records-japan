import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { z } from 'zod';

const keySchema = z.string().regex(/^[a-z][a-z0-9_]*$/);
const booleanSchema = z.enum(['true', 'false']).transform(value => value === 'true');
const optionalText = z.string().transform(value => value === '' ? null : value);
const homeUrl = z.string().url().refine(value => /^https?:\/\//.test(value), 'HTTP(S) only');
const featureFlagSchema = z.object({
  key: keySchema,
  enabled: booleanSchema,
  description: z.string().min(1),
}).strict();
const resourceSchema = z.object({
  key: keySchema,
  name: z.string().min(1),
  kind: z.enum(['checklist', 'guide', 'board', 'regional_site', 'observation', 'specimen', 'literature']),
  home_url: homeUrl,
  taxon_url_template: z.string().refine(value => value === '' || /^https?:\/\//.test(value)).transform(value => value === '' ? null : value),
  owner_note: optionalText,
  license_note: optionalText,
  permission: z.enum(['not_requested', 'requested', 'home_link_only', 'deep_link_ok', 'data_ok', 'declined']),
  enabled: booleanSchema,
}).strict();

/** RFC 4180-style CSV, including quoted commas/newlines and escaped quotes. */
export function parseCsv(source: string): Record<string, string>[] {
  const rows: string[][] = [];
  let row: string[] = [];
  let cell = '';
  let quoted = false;
  let afterQuote = false;
  const text = source.replace(/^\uFEFF/, '');
  const finishCell = () => { row.push(cell); cell = ''; afterQuote = false; };
  const finishRow = () => { finishCell(); rows.push(row); row = []; };
  for (let index = 0; index < text.length; index++) {
    const char = text[index];
    if (quoted) {
      if (char === '"' && text[index + 1] === '"') { cell += '"'; index++; }
      else if (char === '"') { quoted = false; afterQuote = true; }
      else cell += char;
    } else if (char === ',') finishCell();
    else if (char === '\n' || char === '\r') {
      if (char === '\r' && text[index + 1] === '\n') index++;
      finishRow();
    } else if (char === '"' && cell === '' && !afterQuote) quoted = true;
    else {
      if (afterQuote || char === '"') throw new Error('Malformed CSV quote');
      cell += char;
    }
  }
  if (quoted) throw new Error('Unclosed CSV quote');
  if (cell !== '' || row.length !== 0 || afterQuote) finishRow();
  const headers = rows.shift();
  if (!headers || headers.some(value => value === '') || new Set(headers).size !== headers.length) throw new Error('Invalid CSV headers');
  return rows.map((values, index) => {
    if (values.length !== headers.length) throw new Error(`CSV row ${index + 2}: wrong column count`);
    return Object.fromEntries(headers.map((name, column) => [name, values[column] ?? '']));
  });
}

function ensureUniqueKeys(rows: { key: string }[]): void {
  const keys = rows.map(row => row.key);
  if (new Set(keys).size !== keys.length) throw new Error('Duplicate seed keys');
}

export function parseSeedData(featureCsv: string, resourceCsv: string) {
  const flags = z.array(featureFlagSchema).min(1).parse(parseCsv(featureCsv));
  const resources = z.array(resourceSchema).min(1).parse(parseCsv(resourceCsv));
  ensureUniqueKeys(flags);
  ensureUniqueKeys(resources);
  return { flags, resources };
}

const sqlValue = (value: string | boolean | null): string =>
  value === null ? 'null' : typeof value === 'boolean' ? String(value) : `'${value.replaceAll("'", "''")}'`;
const sha256 = (source: string) => createHash('sha256').update(source).digest('hex');

export function generateSeedSql(featureCsv: string, resourceCsv: string): string {
  const { flags, resources } = parseSeedData(featureCsv, resourceCsv);
  const flagRows = flags.map(row => `  (${[row.key, row.enabled, row.description].map(sqlValue).join(', ')})`);
  const resourceRows = resources.map(row => `  (${[row.key, row.name, row.kind, row.home_url, row.taxon_url_template, row.owner_note, row.license_note, row.permission, row.enabled].map(sqlValue).join(', ')})`);
  return [
    '-- Generated by pnpm seed:generate. Sources: seed/feature_flags.csv, seed/external_resources.csv.',
    `-- feature_flags.csv SHA-256: ${sha256(featureCsv)}`,
    `-- external_resources.csv SHA-256: ${sha256(resourceCsv)}`,
    '-- Existing keys are preserved, including owner-approved settings.',
    'begin;',
    'insert into public.feature_flags (key, enabled, description) values',
    flagRows.join(',\n'),
    'on conflict (key) do nothing;',
    'insert into public.external_resources (key, name, kind, home_url, taxon_url_template, owner_note, license_note, permission, enabled) values',
    resourceRows.join(',\n'),
    'on conflict (key) do nothing;',
    'commit;',
    '',
  ].join('\n');
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const result = generateSeedSql(readFileSync('seed/feature_flags.csv', 'utf8'), readFileSync('seed/external_resources.csv', 'utf8'));
  writeFileSync('supabase/seed.sql', result);
  console.log('supabase/seed.sql を生成しました。');
}
